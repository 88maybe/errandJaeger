// Saves real OpenStreetMap places for the Boston core into data/osm-snapshot.json.
// The app uses this copy when no Overpass server answers (before falling back to our small hand-written list).
//
// Run:  npm run snapshot:places      (only writes the file if every category came back)
// Data © OpenStreetMap contributors, ODbL 1.0 (https://www.openstreetmap.org/copyright).
import { writeFileSync } from "node:fs";
import { KINDS } from "../lib/nearby/categories";
import { kindQuery, overpass, toNearby } from "../lib/nearby/osm";
import type { NearbyPlace } from "../lib/nearby/types";

// Boston core: Allston/BU to East Boston, South End to Cambridge (south, west, north, east).
const BBOX: [number, number, number, number] = [42.325, -71.125, 42.375, -71.025];
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

async function main() {
  const all: NearbyPlace[] = [];
  const counts: string[] = [];
  for (const kind of KINDS) {
    let elements = null;
    for (let attempt = 0; attempt < 3 && !elements; attempt++) {
      if (attempt > 0) await sleep(5000 * attempt);
      elements = await overpass(kindQuery(kind, { bbox: BBOX }), { perMirrorMs: 25_000, budgetMs: 60_000 });
    }
    if (!elements) {
      console.error(`${kind.label}: no Overpass server answered. Nothing written.`);
      process.exit(1);
    }
    const places = toNearby(kind, elements);
    all.push(...places);
    counts.push(`${kind.label}: ${places.length}`);
    console.log(`${kind.label}: ${places.length} places (${places.filter((p) => p.hours).length} with readable hours)`);
    await sleep(1500); // be gentle with the public servers
  }
  const body = {
    _note: "GENERATED by scripts/osm-snapshot.ts (npm run snapshot:places). Data © OpenStreetMap contributors, ODbL 1.0. Hours are as mapped on OSM: not verified.",
    fetchedAt: new Date().toISOString(),
    bbox: BBOX,
    places: all,
  };
  writeFileSync(new URL("../data/osm-snapshot.json", import.meta.url), JSON.stringify(body) + "\n");
  console.log(`\nSaved ${all.length} places to data/osm-snapshot.json (${counts.join(", ")}).`);
}

main();
